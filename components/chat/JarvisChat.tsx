"use client";

import { ArrowUp, Check, Loader2, Mic, Plus, RefreshCw, Square, X } from "lucide-react";
import Link from "next/link";
import { useRouter } from "next/navigation";
import { useEffect, useRef, useState } from "react";
import { addWidgetAction } from "@/app/board/actions";
import { streamSSE } from "@/lib/sse-client";
import { AnswerView } from "./AnswerView";
import { ScaledPreview } from "./ScaledPreview";
import { newAnswer, streamAgent, type AnswerTurn } from "./agent-client";
import { useConnected } from "@/components/integrations/connect";
import { ConnectCard } from "@/components/integrations/ConnectCard";
import type { ToolkitId } from "@/lib/integrations/catalog";
import type { Board, WidgetDraft } from "@/lib/types";
import { Orb } from "@/components/ui/Orb";
import { WidgetRenderer } from "@/components/widgets";

type Question = { question: string; options: string[] };
type Approach = { label: string; idea: string };
type AssistantTurn = {
  role: "assistant";
  content: string;
  streaming: boolean;
  questions?: Question[];
  approaches?: Approach[];
  /** Three design slots (A, B, C); null while designing or if one failed. */
  options: (WidgetDraft | null)[];
  failed: number[];
  /** Designs regenerated by an edit in this turn (others were kept). */
  updated?: number[];
  /** Apps this widget needs that aren't connected yet. */
  connects?: Array<{ toolkit: ToolkitId; reason: string }>;
  via?: string;
};
type Turn = { role: "user"; content: string } | AssistantTurn | AnswerTurn | { role: "error"; content: string };

const LETTERS = ["A", "B", "C"];
const SUGGESTIONS = ["A water intake tracker with 8 glasses", "Track my project", "A reading log with a weekly pages chart", "Morning routine checklist"];

export function JarvisChat({ boards, initialBoardId, initialPrompt }: { boards: Board[]; initialBoardId: string; initialPrompt: string }) {
  const router = useRouter();
  const [turns, setTurns] = useState<Turn[]>([]);
  const [input, setInput] = useState("");
  const [busy, setBusy] = useState(false);
  const [picked, setPicked] = useState(0);
  // Whether the user actually chose a design (vs. the default highlight on A).
  const [userPicked, setUserPicked] = useState(false);
  const [boardId, setBoardId] = useState(initialBoardId);
  const [adding, setAdding] = useState(false);
  const [answers, setAnswers] = useState<Record<number, string>>({});
  const abortRef = useRef<AbortController | null>(null);
  const endRef = useRef<HTMLDivElement>(null);

  useEffect(() => () => abortRef.current?.abort(), []);

  const lastAssistantIndex = turns.findLastIndex((t) => t.role === "assistant");
  const latest = lastAssistantIndex >= 0 ? (turns[lastAssistantIndex] as AssistantTurn) : null;
  const latestDesigns = [...turns].reverse().find((t): t is AssistantTurn => t.role === "assistant" && t.options.some(Boolean));

  function patchLast(fn: (t: AssistantTurn) => AssistantTurn) {
    setTurns((all) => {
      const last = all[all.length - 1];
      if (!last || last.role !== "assistant") return all;
      return [...all.slice(0, -1), fn(last)];
    });
  }

  /**
   * Entry point for every message: Jarvis answers questions directly (with
   * tools) and only goes to the designer when the user clearly wants a widget.
   */
  async function ask(text: string, base: Turn[] = turns, selectedOverride?: number, forceWidget = false) {
    const content = text.trim();
    if (!content || busy) return;
    if (forceWidget) return design(content, base, selectedOverride);
    const next: Turn[] = [...base, { role: "user", content }];
    setTurns([...next, newAnswer(content)]);
    setInput("");
    setBusy(true);
    const ac = new AbortController();
    abortRef.current = ac;
    const update = (fn: (t: AnswerTurn) => AnswerTurn) =>
      setTurns((all) => {
        const last = all[all.length - 1];
        return last?.role === "answer" ? [...all.slice(0, -1), fn(last)] : all;
      });
    let routed: "widget" | "answer" = "answer";
    try {
      routed = await streamAgent(
        {
          messages: next
            .filter((t) => t.role !== "error")
            .map((t) => ({ role: t.role === "user" ? ("user" as const) : ("assistant" as const), content: t.content })),
          boardId,
          designsShown: Boolean(latestDesigns),
        },
        update,
        ac.signal,
      );
    } catch (err) {
      if (!ac.signal.aborted) update((t) => ({ ...t, error: err instanceof Error ? err.message : "Jarvis hit an error." }));
    }
    update((t) => ({ ...t, streaming: false }));
    setBusy(false);
    if (routed === "widget") {
      setTurns(base);
      await design(content, base, selectedOverride);
    }
  }

  /** Re-runs the last question after location is shared or an app is connected. */
  function resumeAnswer(index: number) {
    const q = turns[index];
    if (!q || q.role !== "answer") return;
    void ask(q.question, turns.slice(0, index - 1));
  }

  async function design(content: string, base: Turn[], selectedOverride?: number) {
    const next: Turn[] = [...base, { role: "user", content }];
    const history = next
      .filter((t) => t.role !== "error")
      .map((t) => {
        if (t.role === "answer") return { role: "assistant", content: t.content };
        if (t.role !== "assistant") return { role: "user", content: t.content };
        const extra = t.questions?.length
          ? ` I asked: ${t.questions.map((q) => q.question).join(" ")}`
          : t.options.some(Boolean)
            ? ` Designs shown: ${t.options.map((o, i) => (o ? `${LETTERS[i]} "${o.label}"` : "")).filter(Boolean).join(", ")}.`
            : "";
        return { role: "assistant", content: t.content + extra };
      });
    const prev = [...next].reverse().find((t): t is AssistantTurn => t.role === "assistant" && t.options.some(Boolean));
    setTurns([...next, { role: "assistant", content: "", streaming: true, options: [], failed: [] }]);
    setInput("");
    setAnswers({});
    setBusy(true);
    const ac = new AbortController();
    abortRef.current = ac;
    let failedMsg: string | null = null;
    try {
      await streamSSE(
        "/api/jarvis/designs",
        {
          history,
          previous: prev?.options ?? null,
          selected: selectedOverride ?? (prev && userPicked ? picked : null),
          boardName: boards.find((b) => b.id === boardId)?.name ?? null,
        },
        (event, data) => {
          if (event === "meta") patchLast((t) => ({ ...t, via: String(data.label ?? "") }));
          else if (event === "fallback") patchLast((t) => ({ ...t, via: `${data.label} (fallback)` }));
          else if (event === "text") patchLast((t) => ({ ...t, content: t.content + String(data.delta) }));
          else if (event === "connect") patchLast((t) => ({ ...t, connects: [...(t.connects ?? []), { toolkit: data.toolkit as ToolkitId, reason: String(data.reason ?? "") }] }));
          else if (event === "questions") patchLast((t) => ({ ...t, questions: data.questions as Question[] }));
          else if (event === "plan") {
            const revise = data.revise as number[] | null;
            patchLast((t) => ({
              ...t,
              approaches: data.approaches as Approach[],
              options: [0, 1, 2].map((i) => (revise && !revise.includes(i) ? (prev?.options[i] ?? null) : null)),
              updated: revise ?? undefined,
            }));
            if (revise?.length) {
              // Keep the selection on the edited design.
              setPicked((p) => (revise.includes(p) ? p : revise[0]));
              setUserPicked(true);
            } else {
              setPicked(0);
              setUserPicked(false);
            }
          } else if (event === "option") {
            const i = Number(data.index);
            patchLast((t) => {
              const opts = [...t.options];
              while (opts.length < 3) opts.push(null);
              opts[i] = data.draft as WidgetDraft;
              return { ...t, options: opts };
            });
          } else if (event === "optionFailed") patchLast((t) => ({ ...t, failed: [...t.failed, Number(data.index)] }));
          else if (event === "error") failedMsg = String(data.message);
        },
        ac.signal,
      );
    } catch (e) {
      if (!ac.signal.aborted) failedMsg = e instanceof Error ? e.message : "Something went wrong.";
    }
    setTurns((all) => {
      const last = all[all.length - 1];
      let out = all;
      if (last?.role === "assistant") {
        const useful = last.content.trim() || last.questions?.length || last.options.some(Boolean);
        out = useful ? [...all.slice(0, -1), { ...last, content: last.content.trim(), streaming: false }] : all.slice(0, -1);
      }
      if (ac.signal.aborted) return [...out, { role: "error", content: "Stopped." }];
      return failedMsg ? [...out, { role: "error", content: failedMsg }] : out;
    });
    setBusy(false);
  }

  useConnected((_tk, ok) => {
    if (!ok) return;
    const i = turns.findLastIndex((t) => t.role === "answer" && (t.halt?.kind === "connect" || t.connect));
    if (i >= 0) resumeAnswer(i);
  });

  // Auto-send the prompt passed from the board. A timer (cleared on cleanup)
  // keeps React StrictMode's mount/unmount/mount from sending it twice.
  useEffect(() => {
    if (!initialPrompt) return;
    // Prompts handed over from the board were already routed to the designer.
    const t = setTimeout(() => void ask(initialPrompt, [], undefined, true), 0);
    return () => clearTimeout(t);
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [initialPrompt]);

  useEffect(() => {
    endRef.current?.scrollIntoView({ behavior: "smooth", block: "end" });
  }, [turns.length, busy]);

  async function addToBoard() {
    const draft = latestDesigns?.options[picked];
    if (!draft) return;
    setAdding(true);
    try {
      await addWidgetAction(boardId, draft);
      router.push(`/board?b=${boardId}`);
      router.refresh();
    } catch {
      setAdding(false);
      setTurns((t) => [...t, { role: "error", content: "Couldn't add that widget. Try again." }]);
    }
  }

  function sendAnswers(questions: Question[]) {
    const parts = questions.map((q, i) => (answers[i] ? `${q.question} → ${answers[i]}` : null)).filter(Boolean);
    const extra = input.trim();
    const msg = [parts.join("\n"), extra].filter(Boolean).join("\n");
    // Answering "Which design should I change?" also selects that design.
    const chosen = Object.values(answers).map((a) => /^Design ([ABC])\b/.exec(a ?? "")?.[1]).find(Boolean);
    const idx = chosen ? LETTERS.indexOf(chosen) : -1;
    if (idx >= 0) {
      setPicked(idx);
      setUserPicked(true);
    }
    // Answers to the designer's own questions go straight back to the designer.
    if (msg) void ask(msg, turns, idx >= 0 ? idx : undefined, true);
  }

  const lastUser = [...turns].reverse().find((t) => t.role === "user")?.content;
  const placeholder = latest?.questions?.length ? "Answer in your own words, or pick options above" : latestDesigns ? (userPicked ? `Ask for changes to design ${LETTERS[picked]}, or name a letter` : "Ask for changes, like “make B more compact”") : "Describe the widget you want";

  return (
    <>
      <header className="flex flex-wrap items-center gap-3">
        <h1 className="m-0 flex-1 text-lg font-semibold tracking-[-0.015em]">New widget</h1>
        <label className="inline-flex h-[38px] items-center gap-2 rounded-full border border-line bg-card pl-3.5 pr-2 text-[13px] text-muted">
          Add to
          <select value={boardId} onChange={(e) => setBoardId(e.target.value)} className="bg-transparent font-medium text-text outline-none">
            {boards.map((b) => (
              <option key={b.id} value={b.id}>
                {b.name}
              </option>
            ))}
          </select>
        </label>
        <Link href={`/board?b=${boardId}`} aria-label="Close" className="flex h-[42px] w-[42px] items-center justify-center rounded-full border border-line bg-card">
          <X size={18} />
        </Link>
      </header>

      <div className="mx-auto flex w-full max-w-[1040px] flex-1 flex-col gap-5">
        {turns.length === 0 && !busy && (
          <div className="flex flex-1 flex-col items-center justify-center gap-4 py-10 text-center">
            <Orb size={96} glow />
            <p className="m-0 text-[22px] font-semibold tracking-[-0.02em]">What should this widget do?</p>
            <p className="m-0 max-w-md text-muted">Describe it in your own words. Jarvis checks it understood, asks only if something&apos;s unclear, then designs three new options for you to pick from.</p>
            <div className="flex max-w-2xl flex-wrap justify-center gap-2">
              {SUGGESTIONS.map((s) => (
                <button key={s} type="button" onClick={() => ask(s)} className="h-9 rounded-full border border-line bg-card px-3.5 text-[13px] font-medium text-muted hover:text-text">
                  {s}
                </button>
              ))}
            </div>
          </div>
        )}

        {turns.map((t, i) => {
          if (t.role === "user")
            return (
              <div key={i} className="max-w-[80%] self-end whitespace-pre-wrap rounded-[22px_22px_6px_22px] bg-ink px-[18px] py-3.5 text-base text-ink-text">
                {t.content}
              </div>
            );
          if (t.role === "answer")
            return (
              <AnswerView
                key={i}
                turn={t}
                onResume={() => resumeAnswer(i)}
                onHalt={(h) => setTurns((all) => all.map((x, j) => (j === i && x.role === "answer" ? { ...x, halt: h } : x)))}
                footer={
                  t.content && i === turns.length - 1 ? (
                    <div className="flex flex-wrap items-center gap-2">
                      <button
                        type="button"
                        onClick={() => ask(`Make a widget for: ${t.question}`, turns, undefined, true)}
                        className="inline-flex h-8 items-center gap-1.5 whitespace-nowrap rounded-full border border-line px-3 text-[12px] font-medium text-muted hover:text-text"
                      >
                        <Plus size={13} /> Turn into a widget
                      </button>
                      {t.via && <span className="text-xs text-faint">via {t.via}</span>}
                    </div>
                  ) : null
                }
              />
            );
          if (t.role === "error")
            return (
              <p key={i} role="alert" className="m-0 self-start rounded-full bg-card px-4 py-2 text-coral-text">
                {t.content}
              </p>
            );
          const isLatest = i === lastAssistantIndex;
          const hasDesigns = Boolean(t.approaches) || t.options.some(Boolean);
          return (
            <div key={i} className="flex gap-3.5">
              <Orb size={34} pulse={t.streaming} />
              <div className={`flex min-w-0 flex-1 flex-col gap-4 ${isLatest ? "" : "opacity-60"}`}>
                <p className="m-0 pt-1 text-base" aria-live="polite">
                  {t.content || (t.streaming ? <span className="text-muted">Jarvis is reading your request…</span> : null)}
                  {t.streaming && t.content && !hasDesigns && !t.questions && (
                    <span aria-hidden className="ml-0.5 inline-block h-4 w-[2px] translate-y-0.5 animate-pulse bg-coral" />
                  )}
                  {isLatest && !t.streaming && t.options.some(Boolean) && <span className="text-faint"> Pick one.</span>}
                </p>

                {isLatest && t.connects?.map((c) => <ConnectCard key={c.toolkit} toolkit={c.toolkit} reason={c.reason} />)}
                {t.questions?.length ? (
                  isLatest ? (
                    <div className="flex flex-col gap-3 rounded-[22px] border border-line bg-card p-4">
                      {t.questions.map((q, qi) => (
                        <div key={qi} className="flex flex-col gap-2">
                          <p className="m-0 font-semibold">{q.question}</p>
                          <div role="radiogroup" aria-label={q.question} className="flex flex-wrap gap-2">
                            {q.options.map((o) => {
                              const on = answers[qi] === o;
                              return (
                                <button
                                  key={o}
                                  type="button"
                                  role="radio"
                                  aria-checked={on}
                                  onClick={() => setAnswers((a) => ({ ...a, [qi]: on ? "" : o }))}
                                  className={`h-9 rounded-full border px-3.5 text-[13px] font-medium transition-colors ${on ? "border-ink bg-ink text-ink-text" : "border-line text-muted hover:text-text"}`}
                                >
                                  {o}
                                </button>
                              );
                            })}
                          </div>
                        </div>
                      ))}
                      <div className="flex flex-wrap items-center gap-2 pt-1">
                        <button
                          type="button"
                          disabled={busy || (!Object.values(answers).some(Boolean) && !input.trim())}
                          onClick={() => sendAnswers(t.questions!)}
                          className="inline-flex h-10 items-center gap-2 rounded-full bg-ink px-4 text-[13px] font-semibold text-ink-text disabled:opacity-40"
                        >
                          <ArrowUp size={15} /> Continue
                        </button>
                        <span className="text-xs text-faint">or type your answer below</span>
                      </div>
                    </div>
                  ) : (
                    <p className="m-0 text-[13px] text-muted">{t.questions.map((q) => q.question).join(" ")}</p>
                  )
                ) : null}

                {hasDesigns &&
                  (isLatest ? (
                    <>
                      <div role="radiogroup" aria-label="Widget designs" className="flex flex-wrap items-start gap-3.5">
                        {[0, 1, 2].map((oi) => {
                          const o = t.options[oi] ?? null;
                          const label = o?.label ?? t.approaches?.[oi]?.label ?? `Design ${LETTERS[oi]}`;
                          if (!o) {
                            const failed = t.failed.includes(oi);
                            return (
                              <div key={oi} aria-hidden className="flex min-h-[300px] min-w-0 flex-[1_1_280px] flex-col gap-2.5 rounded-[26px] border-2 border-transparent bg-card2 p-3">
                                <span className="truncate font-mono text-xs font-semibold uppercase text-faint">
                                  {LETTERS[oi]} · {label} · {failed ? "couldn't design" : "designing…"}
                                </span>
                                <div className="flex flex-1 flex-col items-center justify-center gap-2 rounded-[22px] bg-card p-4 text-center">
                                  {failed ? <X size={20} className="text-faint" /> : <Orb size={40} pulse />}
                                  {t.approaches?.[oi]?.idea && <span className="text-xs text-faint">{t.approaches[oi].idea}</span>}
                                </div>
                              </div>
                            );
                          }
                          const on = oi === picked;
                          return (
                            <div
                              key={oi}
                              role="radio"
                              aria-checked={on}
                              aria-label={`Design ${LETTERS[oi]}: ${o.label}`}
                              tabIndex={on ? 0 : -1}
                              onClick={() => {
                                setPicked(oi);
                                setUserPicked(true);
                              }}
                              onKeyDown={(e) => {
                                if (e.key === "ArrowRight" || e.key === "ArrowDown") setPicked((p) => (p + 1) % 3);
                                if (e.key === "ArrowLeft" || e.key === "ArrowUp") setPicked((p) => (p + 2) % 3);
                                if (e.key === " " || e.key === "Enter") setPicked(oi);
                                setUserPicked(true);
                              }}
                              className={`flex min-w-0 flex-[1_1_280px] cursor-pointer flex-col gap-2.5 rounded-[26px] border-2 p-3 transition-colors ${on ? "border-coral" : "border-transparent bg-card2"}`}
                              style={on ? { background: "color-mix(in srgb, var(--coral) 8%, var(--shell))" } : undefined}
                            >
                              <span className="flex w-full items-center gap-2">
                                <span className="flex-1 truncate font-mono text-xs font-semibold uppercase text-muted">
                                  {LETTERS[oi]} · {o.label} <span className="text-faint">· {o.w ?? "?"}×{o.h ?? "?"}</span>
                                </span>
                                {t.updated?.includes(oi) && !t.streaming && (
                                  <span className="shrink-0 rounded-full bg-coral px-2 py-0.5 text-[11px] font-semibold text-white">Updated {LETTERS[oi]}</span>
                                )}
                                <span aria-hidden className={`flex h-[22px] w-[22px] items-center justify-center rounded-full ${on ? "bg-coral text-white" : "border-[1.5px] border-faint text-transparent"}`}>
                                  <Check size={12} strokeWidth={3} />
                                </span>
                              </span>
                              <ScaledPreview w={o.w ?? 4} h={o.h ?? 7}>
                                <WidgetRenderer type={o.type} title={o.title} size={o.size} config={o.config} data={null} preview />
                              </ScaledPreview>
                            </div>
                          );
                        })}
                      </div>
                      {!t.streaming && t.options.some(Boolean) && (
                        <div className="flex flex-wrap items-center gap-2.5">
                          <button
                            type="button"
                            onClick={addToBoard}
                            disabled={adding || !t.options[picked]}
                            className="inline-flex h-[46px] items-center gap-2 rounded-full bg-ink px-[22px] font-semibold text-ink-text disabled:opacity-60"
                          >
                            {adding ? <Loader2 size={16} className="animate-spin" /> : <Plus size={16} />}
                            Add design {LETTERS[picked]} to board
                          </button>
                          <button
                            type="button"
                            disabled={busy || !lastUser}
                            onClick={() => ask("Show me 3 completely different designs.")}
                            className="inline-flex h-[46px] items-center gap-2 rounded-full border border-line bg-card px-[18px] font-medium disabled:opacity-60"
                          >
                            <RefreshCw size={15} /> Show 3 more
                          </button>
                          {t.via && <span className="text-[13px] text-faint">via {t.via}</span>}
                        </div>
                      )}
                    </>
                  ) : (
                    <p className="m-0 font-mono text-xs text-muted">{t.options.map((o, oi) => (o ? `${LETTERS[oi]} · ${o.label}` : "")).filter(Boolean).join("   ")}</p>
                  ))}
              </div>
            </div>
          );
        })}
        <div ref={endRef} />

        <form
          onSubmit={(e) => {
            e.preventDefault();
            if (latest?.questions?.length && !busy) sendAnswers(latest.questions);
            else void ask(input);
          }}
          className="field sticky bottom-2 mt-auto flex flex-wrap items-center gap-2.5 rounded-[28px] border border-line bg-card py-3.5 pl-5 pr-3.5 shadow-card"
        >
          <label className="min-w-0 flex-[1_1_240px]">
            <span className="sr-only">Message Jarvis</span>
            <input
              autoFocus={!initialPrompt}
              value={input}
              onChange={(e) => setInput(e.target.value)}
              placeholder={placeholder}
              className="h-[42px] w-full bg-transparent text-base outline-none placeholder:text-faint"
            />
          </label>
          <button type="button" aria-label="Speak instead (coming soon)" title="Voice is coming soon" aria-disabled className="flex h-11 w-11 items-center justify-center rounded-full border border-line text-muted">
            <Mic size={18} strokeWidth={1.7} />
          </button>
          {busy ? (
            <button type="button" onClick={() => abortRef.current?.abort()} aria-label="Stop Jarvis" className="flex h-11 w-11 items-center justify-center rounded-full bg-ink text-ink-text">
              <Square size={14} fill="currentColor" />
            </button>
          ) : (
            <button type="submit" aria-label="Send" disabled={!input.trim() && !Object.values(answers).some(Boolean)} className="flex h-11 w-11 items-center justify-center rounded-full bg-coral text-white disabled:opacity-50">
              <ArrowUp size={18} strokeWidth={2} />
            </button>
          )}
        </form>
      </div>
    </>
  );
}
